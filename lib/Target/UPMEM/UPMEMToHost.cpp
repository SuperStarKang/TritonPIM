#include "triton-shared/Target/UPMEM/UPMEMTranslations.h"
#include "triton-shared/Dialect/PIMVendor/UPMEM/IR/UPMEMDialect.h"

#include "mlir/Dialect/Func/IR/FuncOps.h"
#include "mlir/Dialect/MemRef/IR/MemRef.h"
#include "mlir/IR/BuiltinOps.h"
#include "mlir/Tools/mlir-translate/Translation.h"
#include "llvm/Support/raw_ostream.h"

using namespace mlir;

// UPMEM IR을 walk해 host C++를 emit한다.
// - local_gemm{m,n,k}에서 크기를 상수로 박는다 (no-split single tile).
// - device_func 심볼명으로 로드할 .elf 이름을 정한다.
// - host 함수 이름은 <func 이름>_host.
// - B(K,N)를 Bt(N,K)로 전치해 올리고, A/Bt/C를 MRAM 심볼로 copy한다.
static LogicalResult translateUPMEMToHost(ModuleOp module, raw_ostream &os) {
  upmem::LocalGemmOp gemm;
  module.walk([&](upmem::LocalGemmOp g) { gemm = g; });
  upmem::DeviceFuncOp dev;
  module.walk([&](upmem::DeviceFuncOp d) { dev = d; });
  func::FuncOp host;
  module.walk([&](func::FuncOp f) {
    if (!host)
      host = f;
  });

  if (!gemm || !dev || !host)
    return module.emitError(
        "upmem-to-host: expected upmem.local_gemm, upmem.device_func, and a host func");

  uint64_t M = gemm.getM();
  uint64_t N = gemm.getN();
  uint64_t K = gemm.getK();
  std::string hostName = (host.getName() + "_host").str();
  std::string binary = (dev.getSymName() + ".elf").str();

  os << "// generated by triton-shared-translate (upmem-to-host)\n";
  os << "#include <dpu.h>\n";
  os << "#include <stdint.h>\n";
  os << "#include <stdlib.h>\n\n";
  os << "#ifndef DPU_BINARY\n#define DPU_BINARY \"" << binary << "\"\n#endif\n\n";
  os << "extern \"C\" void " << hostName << "(float* A, float* B, float* C) {\n";
  os << "  uint32_t M = " << M << ", N = " << N << ", K = " << K << ";\n";
  os << "  struct dpu_set_t set;\n";
  os << "  DPU_ASSERT(dpu_alloc(1, NULL, &set));\n";
  os << "  DPU_ASSERT(dpu_load(set, DPU_BINARY, NULL));\n";
  os << "  // B(K,N) -> Bt(N,K): device가 행을 연속으로 읽도록 전치\n";
  os << "  float* Bt = (float*)malloc((size_t)N * K * sizeof(float));\n";
  os << "  for (uint32_t kk = 0; kk < K; ++kk)\n";
  os << "    for (uint32_t j = 0; j < N; ++j) Bt[j * K + kk] = B[kk * N + j];\n";
  os << "  DPU_ASSERT(dpu_copy_to(set, \"M\", 0, &M, sizeof(uint32_t)));\n";
  os << "  DPU_ASSERT(dpu_copy_to(set, \"N\", 0, &N, sizeof(uint32_t)));\n";
  os << "  DPU_ASSERT(dpu_copy_to(set, \"K\", 0, &K, sizeof(uint32_t)));\n";
  os << "  DPU_ASSERT(dpu_copy_to(set, \"A_mram\", 0, A, (size_t)M * K * sizeof(float)));\n";
  os << "  DPU_ASSERT(dpu_copy_to(set, \"Bt_mram\", 0, Bt, (size_t)N * K * sizeof(float)));\n";
  os << "  DPU_ASSERT(dpu_launch(set, DPU_SYNCHRONOUS));\n";
  os << "  DPU_ASSERT(dpu_copy_from(set, \"C_mram\", 0, C, (size_t)M * N * sizeof(float)));\n";
  os << "  free(Bt);\n";
  os << "  DPU_ASSERT(dpu_free(set));\n";
  os << "}\n";
  return success();
}

void mlir::triton::registerUPMEMToHostTranslation() {
  TranslateFromMLIRRegistration reg(
      "upmem-to-host", "emit UPMEM host C++ from UPMEM IR",
      translateUPMEMToHost, [](DialectRegistry &registry) {
        registry.insert<func::FuncDialect, memref::MemRefDialect,
                        upmem::UPMEMDialect>();
      });
}
