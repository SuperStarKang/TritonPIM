// scf.for의 step(=BLOCK 크기)을 컴파일타임 상수로 읽는다. build-pim-offload가 항상 상수 step을
// 내므로(BLOCK은 Triton constexpr) 상수가 아니면 IR 불변식 위반 — 그대로 터지게 둔다(fail-fast).
static int64_t constStep(scf::ForOp f) {
  auto c = f.getStep().getDefiningOp<arith::ConstantOp>();
  return cast<IntegerAttr>(c.getValue()).getInt();
}

// MLIR element type → C 타입 이름. 지원: f32/f64/i8/i16/i32/i64. 미지원이면 빈 문자열.
static std::string cType(Type t) {
  if (t.isF32())
    return "float";
  if (t.isF64())
    return "double";
  if (auto it = dyn_cast<IntegerType>(t)) {
    switch (it.getWidth()) {
    case 8:  return "int8_t";
    case 16: return "int16_t";
    case 32: return "int32_t";
    case 64: return "int64_t";
    }
  }
  return "";
}

// device_func 본문의 gemm nest에서 BLOCK_M/N/K와 dtype을 추출한다 (faithful-body, O1.4a).
// matmul을 감싸는 3중 scf.for의 step = (kc→BK, tn→BN, tm→BM). dtype은 입력(Tin, matmul 피연산자)과
// 누적/출력(Tacc, matmul outs)을 따로 읽는다 — int8 입력 + int32 누적 같은 mixed도 표현 가능.
static LogicalResult extractGemmBlocks(ModuleOp module, upmem::DeviceFuncOp dev,
                                       uint64_t &blockM, uint64_t &blockN,
                                       uint64_t &blockK, std::string &inCType,
                                       std::string &accCType) {
  linalg::MatmulOp mm;
  dev.walk([&](linalg::MatmulOp m) { mm = m; });
  if (!mm)
    return module.emitError("device_func body must contain linalg.matmul (gemm). "
                            "비-gemm 본문 충실 번역은 O1.4b.");
  scf::ForOp kcFor = mm->getParentOfType<scf::ForOp>();
  scf::ForOp tnFor = kcFor ? kcFor->getParentOfType<scf::ForOp>() : nullptr;
  scf::ForOp tmFor = tnFor ? tnFor->getParentOfType<scf::ForOp>() : nullptr;
  if (!kcFor || !tnFor || !tmFor)
    return module.emitError("gemm 본문은 3중 scf.for(tm/tn/kc) nest여야 한다");
  blockM = constStep(tmFor);
  blockN = constStep(tnFor);
  blockK = constStep(kcFor);
  // matmul operand 0 = A 입력 타일(Tin), 마지막 operand = acc 출력(Tacc).
  Type inElem = cast<MemRefType>(mm->getOperand(0).getType()).getElementType();
  Type accElem =
      cast<MemRefType>(mm->getOperand(mm->getNumOperands() - 1).getType())
          .getElementType();
  inCType = cType(inElem);
  accCType = cType(accElem);
  if (inCType.empty() || accCType.empty())
    return module.emitError("지원하지 않는 element type (f32/f64/i8/i16/i32/i64만)");
  return success();
}

// UPMEM IR을 walk해 DPU C 커널을 emit한다.
// device는 자기 부분행렬(__host M×N, full K)을 BLOCK_M×BLOCK_N 출력 타일로 순회하며,
// 타일마다 K를 BLOCK_K씩 WRAM(aW/bW)에 올려 누적(acc)한다 — GPU shared-memory blocking과 동일.
// cooperative 다중 tasklet: 한 타일을 tasklet들이 함께 계산한다. WRAM 타일 버퍼(aW/bW/acc)는
// 전 tasklet이 공유(크기는 NR_TASKLETS와 무관, 1타일분)하고, BLOCK_M 행을 tasklet이 분할한다.
// bW는 모든 tasklet이 전체를 읽으므로 협력 로드 후 barrier로 동기화한다.
// 이 cooperative-shared-bW 구조가 bW를 BLOCK_M개 행에 재사용하는 게 핵심 이점이다 (PGEMM식
//   disjoint-tasklet은 B를 행마다 재로드해 mram_read가 폭증 → 오히려 느림, IMPLEMENT ⑦ 참고).
// BLOCK_M/N/K는 device_func 본문 gemm nest의 scf.for step에서 읽어 컴파일 상수로 박는다(faithful-body).
// M/N/K는 BLOCK의 배수 가정.
static LogicalResult translateUPMEMToDevice(ModuleOp module, raw_ostream &os) {
  // faithful-body(O1.4a): device_func 본문(gemm nest)에서 BLOCK을 읽는다.
  // device.c emission은 검증된 gemm 템플릿을 재사용한다(비-gemm 본문 충실 번역은 O1.4b).
  upmem::DeviceFuncOp dev;
  module.walk([&](upmem::DeviceFuncOp d) { dev = d; });
  if (!dev)
    return module.emitError("upmem-to-device: expected upmem.device_func");
  uint64_t blockM, blockN, blockK;
  std::string inT, accT;
  if (failed(extractGemmBlocks(module, dev, blockM, blockN, blockK, inT, accT)))
    return failure();

  os << "// generated by triton-shared-translate (upmem-to-device)\n";
  os << "#include <stdint.h>\n";
  os << "#include <mram.h>\n";
  os << "#include <defs.h>\n";
  os << "#include <barrier.h>\n\n";
  os << "// BLOCK_M/N/K: Triton 블록 = DPU 내부 타일 크기. WRAM 공유 버퍼 크기를 결정한다.\n";
  os << "#define BLOCK_M " << blockM << "\n";
  os << "#define BLOCK_N " << blockN << "\n";
  os << "#define BLOCK_K " << blockK << "\n\n";
  os << "// dtype: Tin=입력(A/B), Tacc=누적·출력(C). IR matmul 피연산자/outs에서 읽음.\n";
  os << "typedef " << inT << " Tin;\n";
  os << "typedef " << accT << " Tacc;\n\n";
  os << "// host가 broadcast로 채우는 이 DPU의 부분행렬 크기 (BLOCK의 배수). K는 full.\n";
  os << "__host uint32_t M;\n";
  os << "__host uint32_t N;\n";
  os << "__host uint32_t K;\n\n";
  os << "// host가 채우는 MRAM 버퍼\n";
  os << "__mram_noinit Tin A_mram[1u << 22];   // (M,K) row-major\n";
  os << "__mram_noinit Tin Bt_mram[1u << 22];  // (N,K) row-major (host가 전치)\n";
  os << "__mram_noinit Tacc C_mram[1u << 22];  // (M,N) row-major\n\n";
  os << "// WRAM 타일 버퍼 — 모든 tasklet이 공유 (크기는 NR_TASKLETS와 무관, 1타일분).\n";
  os << "__dma_aligned Tin aW[BLOCK_M * BLOCK_K];   // A 서브타일 [BLOCK_M, BLOCK_K]\n";
  os << "__dma_aligned Tin bW[BLOCK_N * BLOCK_K];   // Bt 서브타일 [BLOCK_N, BLOCK_K]\n";
  os << "__dma_aligned Tacc acc[BLOCK_M * BLOCK_N]; // 누산기 [BLOCK_M, BLOCK_N]\n\n";
  os << "// NR_TASKLETS는 launcher가 -DNR_TASKLETS=local_lanes로 주입.\n";
  os << "BARRIER_INIT(my_barrier, NR_TASKLETS);\n\n";
  os << "int main() {\n";
  os << "  uint32_t t = me();\n";
  os << "  for (uint32_t tm = 0; tm < M; tm += BLOCK_M) {        // 행-타일\n";
  os << "    for (uint32_t tn = 0; tn < N; tn += BLOCK_N) {      // 열-타일\n";
  os << "      // acc 행을 tasklet이 분할 (자기 행만 init·누적, 공유 안 함)\n";
  os << "      for (uint32_t r = t; r < BLOCK_M; r += NR_TASKLETS)\n";
  os << "        for (uint32_t c = 0; c < BLOCK_N; ++c) acc[r * BLOCK_N + c] = 0;\n";
  os << "      for (uint32_t kc = 0; kc < K; kc += BLOCK_K) {    // K 청크\n";
  os << "        // aW: 자기 행만 로드 (자기 acc 행 계산에만 쓰임)\n";
  os << "        for (uint32_t r = t; r < BLOCK_M; r += NR_TASKLETS)\n";
  os << "          mram_read(&A_mram[(tm + r) * K + kc], &aW[r * BLOCK_K], BLOCK_K * sizeof(Tin));\n";
  os << "        // bW: 모든 tasklet이 전체를 읽으므로 협력 로드\n";
  os << "        for (uint32_t r = t; r < BLOCK_N; r += NR_TASKLETS)\n";
  os << "          mram_read(&Bt_mram[(tn + r) * K + kc], &bW[r * BLOCK_K], BLOCK_K * sizeof(Tin));\n";
  os << "        barrier_wait(&my_barrier);                       // bW 전부 로드 보장\n";
  os << "        // 자기 acc 행 × 전체 bW: acc[r,c] += sum_l aW[r,l]*bW[c,l]\n";
  os << "        for (uint32_t r = t; r < BLOCK_M; r += NR_TASKLETS)\n";
  os << "          for (uint32_t c = 0; c < BLOCK_N; ++c) {\n";
  os << "            Tacc s = 0;\n";
  os << "            for (uint32_t l = 0; l < BLOCK_K; ++l) s += (Tacc)aW[r * BLOCK_K + l] * (Tacc)bW[c * BLOCK_K + l];\n";
  os << "            acc[r * BLOCK_N + c] += s;\n";
  os << "          }\n";
  os << "        barrier_wait(&my_barrier);                       // 다음 kc가 bW 덮어쓰기 전 계산 완료\n";
  os << "      }\n";
  os << "      // acc -> C[tm:+BLOCK_M, tn:+BLOCK_N] (자기 행)\n";
  os << "      for (uint32_t r = t; r < BLOCK_M; r += NR_TASKLETS)\n";
  os << "        mram_write(&acc[r * BLOCK_N], &C_mram[(tm + r) * N + tn], BLOCK_N * sizeof(Tacc));\n";
  os << "      barrier_wait(&my_barrier);                         // 타일 경계\n";
  os << "    }\n";
  os << "  }\n";
  os << "  return 0;\n";
  os << "}\n";
  return success();
}

void mlir::triton::registerUPMEMToDeviceTranslation() {
  TranslateFromMLIRRegistration reg(
      "upmem-to-device", "emit UPMEM DPU C kernel from UPMEM IR",
      translateUPMEMToDevice, [](DialectRegistry &registry) {
        // device_func 본문(faithful-body)이 arith/scf/linalg op을 담으므로 파싱에 필요하다.
        registry.insert<arith::ArithDialect, func::FuncDialect,
                        linalg::LinalgDialect, memref::MemRefDialect,
                        scf::SCFDialect, upmem::UPMEMDialect>();
      });
}
