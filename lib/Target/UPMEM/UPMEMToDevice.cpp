#include "triton-shared/Target/UPMEM/UPMEMTranslations.h"
#include "triton-shared/Dialect/PIMVendor/UPMEM/IR/UPMEMDialect.h"

#include "mlir/Dialect/Func/IR/FuncOps.h"
#include "mlir/Dialect/MemRef/IR/MemRef.h"
#include "mlir/IR/BuiltinOps.h"
#include "mlir/Tools/mlir-translate/Translation.h"
#include "llvm/Support/raw_ostream.h"

using namespace mlir;

// UPMEM IR을 walk해 DPU C 커널을 emit한다.
// device는 자기 부분행렬(__host M×N, full K)을 BLOCK_M×BLOCK_N 출력 타일로 순회하며,
// 타일마다 K를 BLOCK_K씩 WRAM(aW/bW)에 올려 누적(acc)한다 — GPU shared-memory blocking과 동일.
// BLOCK_M/N/K는 local_gemm에서 읽어 컴파일 상수로 박는다(WRAM 버퍼 크기 결정).
// 단일 tasklet 버전(①a). cooperative 다중 tasklet은 다음 단계. M/N/K는 BLOCK의 배수 가정.
static LogicalResult translateUPMEMToDevice(ModuleOp module, raw_ostream &os) {
  upmem::LocalGemmOp gemm;
  module.walk([&](upmem::LocalGemmOp g) { gemm = g; });
  if (!gemm)
    return module.emitError("upmem-to-device: expected upmem.local_gemm");

  // local_gemm의 m/n/k = Triton BLOCK (= DPU 내부 타일 크기, WRAM staging 단위).
  uint64_t blockM = gemm.getM();
  uint64_t blockN = gemm.getN();
  uint64_t blockK = gemm.getK();

  os << "// generated by triton-shared-translate (upmem-to-device)\n";
  os << "#include <stdint.h>\n";
  os << "#include <mram.h>\n";
  os << "#include <defs.h>\n\n";
  os << "// BLOCK_M/N/K: Triton 블록 = DPU 내부 타일 크기. WRAM 버퍼 크기를 결정한다.\n";
  os << "#define BLOCK_M " << blockM << "\n";
  os << "#define BLOCK_N " << blockN << "\n";
  os << "#define BLOCK_K " << blockK << "\n\n";
  os << "// host가 broadcast로 채우는 이 DPU의 부분행렬 크기 (BLOCK의 배수). K는 full.\n";
  os << "__host uint32_t M;\n";
  os << "__host uint32_t N;\n";
  os << "__host uint32_t K;\n\n";
  os << "// host가 채우는 MRAM 버퍼\n";
  os << "__mram_noinit float A_mram[1u << 22];   // (M,K) row-major\n";
  os << "__mram_noinit float Bt_mram[1u << 22];  // (N,K) row-major (host가 전치)\n";
  os << "__mram_noinit float C_mram[1u << 22];   // (M,N) row-major\n\n";
  os << "// WRAM 타일 버퍼 (8바이트 정렬). aW+bW+acc가 WRAM(64KB)에 들어가야 한다.\n";
  os << "__dma_aligned float aW[BLOCK_M * BLOCK_K];   // A 서브타일 [BLOCK_M, BLOCK_K]\n";
  os << "__dma_aligned float bW[BLOCK_N * BLOCK_K];   // Bt 서브타일 [BLOCK_N, BLOCK_K]\n";
  os << "__dma_aligned float acc[BLOCK_M * BLOCK_N];  // 누산기 [BLOCK_M, BLOCK_N]\n\n";
  os << "int main() {\n";
  os << "  if (me() != 0) return 0;  // 단일 tasklet (cooperative 다중 tasklet은 다음 단계)\n";
  os << "  for (uint32_t tm = 0; tm < M; tm += BLOCK_M) {        // 행-타일\n";
  os << "    for (uint32_t tn = 0; tn < N; tn += BLOCK_N) {      // 열-타일\n";
  os << "      for (uint32_t i = 0; i < BLOCK_M * BLOCK_N; ++i) acc[i] = 0.0f;\n";
  os << "      for (uint32_t kc = 0; kc < K; kc += BLOCK_K) {    // K 청크 (WRAM staging)\n";
  os << "        // A[tm:+BLOCK_M, kc:+BLOCK_K] -> aW (행마다 BLOCK_K 연속)\n";
  os << "        for (uint32_t r = 0; r < BLOCK_M; ++r)\n";
  os << "          mram_read(&A_mram[(tm + r) * K + kc], &aW[r * BLOCK_K], BLOCK_K * sizeof(float));\n";
  os << "        // Bt[tn:+BLOCK_N, kc:+BLOCK_K] -> bW\n";
  os << "        for (uint32_t r = 0; r < BLOCK_N; ++r)\n";
  os << "          mram_read(&Bt_mram[(tn + r) * K + kc], &bW[r * BLOCK_K], BLOCK_K * sizeof(float));\n";
  os << "        // acc[r,c] += sum_l aW[r,l]*bW[c,l]  (Bt라 bW[c]가 출력열 c의 K-벡터)\n";
  os << "        for (uint32_t r = 0; r < BLOCK_M; ++r)\n";
  os << "          for (uint32_t c = 0; c < BLOCK_N; ++c) {\n";
  os << "            float s = 0.0f;\n";
  os << "            for (uint32_t l = 0; l < BLOCK_K; ++l) s += aW[r * BLOCK_K + l] * bW[c * BLOCK_K + l];\n";
  os << "            acc[r * BLOCK_N + c] += s;\n";
  os << "          }\n";
  os << "      }\n";
  os << "      // acc -> C[tm:+BLOCK_M, tn:+BLOCK_N]\n";
  os << "      for (uint32_t r = 0; r < BLOCK_M; ++r)\n";
  os << "        mram_write(&acc[r * BLOCK_N], &C_mram[(tm + r) * N + tn], BLOCK_N * sizeof(float));\n";
  os << "    }\n";
  os << "  }\n";
  os << "  return 0;\n";
  os << "}\n";
  return success();
}

void mlir::triton::registerUPMEMToDeviceTranslation() {
  TranslateFromMLIRRegistration reg(
      "upmem-to-device", "emit UPMEM DPU C kernel from UPMEM IR",
      translateUPMEMToDevice, [](DialectRegistry &registry) {
        registry.insert<func::FuncDialect, memref::MemRefDialect,
                        upmem::UPMEMDialect>();
      });
}
