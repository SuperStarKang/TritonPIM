namespace {

// batch 코드. status word 의 bit 15/16/17 이고 {1,2,4,8} 만 표현한다.
// aimx.descriptor_program 의 attribute 하나에서 유일하게 유도한다 — flag enum 에는
// 이 비트가 없다.
uint32_t batchBits(int64_t batch) {
  switch (batch) {
  case 2:
    return 1u << 15;
  case 4:
    return 1u << 16;
  case 8:
    return (1u << 16) | (1u << 15);
  default:
    return 0;
  }
}

// descriptor program 을 C 함수로 낸다. 함수 하나가 program 하나이고, 몸체의 for 문이
// IR 의 scf.for 그대로다. chain 이 아니라 program 을 내므로 크기가 tile 수와 무관하다.
struct DescriptorEmitter {
  CEmitter e;
  DescriptorEmitter(raw_ostream &os) : e(os) {}
  raw_ostream &os() { return e.os; }

  uint32_t batch = 0;

  LogicalResult run(ModuleOp module) {
    os() << "// generated by triton-shared-translate (aimx-to-descriptors)\n"
         << "// descriptor program 하나가 함수 하나다. stub 이 launch 당 한 번만 부른다.\n"
         << "#pragma once\n"
         << "#include \"aimx_runtime.h\"\n\n";
    for (auto prog : module.getOps<aimx::DescriptorProgramOp>())
      if (failed(emitProgram(prog)))
        return failure();
    return success();
  }

  LogicalResult emitProgram(aimx::DescriptorProgramOp prog) {
    batch = batchBits(prog.getBatch());
    Block &body = prog.getBody().front();

    os() << "// aimx.descriptor_program @" << prog.getSymName() << " batch "
         << prog.getBatch() << "\n";
    // cap 은 code 가 담을 수 있는 record 수다. tile 모양이 런타임 값이므로 group 수도
    // 런타임에 정해지고, 넘치면 여기서 **쓰기 전에** 멈춰야 한다 — 참조 구현의
    // assert(desc_idx == num_descr) (matmul.c:179) 와 같은 역할이되 사후가 아니다.
    os() << "static uint32_t aimx_prog_" << prog.getSymName()
         << "(pim_isa_32_t *code, uint32_t cap, uint32_t idx, uint64_t *next, "
            "int fpga_id";
    for (BlockArgument arg : body.getArguments()) {
      std::string n = e.name(arg);
      if (isa<aimx::BufferType>(arg.getType()))
        os() << ", uint64_t " << n;  // PIM DRAM 의 물리 주소
      else if (isa<IndexType>(arg.getType()))
        os() << ", int64_t " << n;
      else
        return prog->emitError("aimx-to-descriptors: a program parameter must "
                               "be an index or an !aimx.buffer");
    }
    os() << ") {\n";
    if (failed(emitBlock(body, 1)))
      return failure();
    os() << "  return idx;\n}\n\n";
    return success();
  }

  LogicalResult emitBlock(Block &block, unsigned depth) {
    for (Operation &op : block)
      if (failed(emitOp(&op, depth)))
        return failure();
    return success();
  }

  LogicalResult emitOp(Operation *op, unsigned depth) {
    if (auto loop = dyn_cast<scf::ForOp>(op))
      return e.emitFor(loop, depth, [&](Block &b, unsigned d) {
        return emitBlock(b, d);
      });
    if (auto desc = dyn_cast<aimx::DescOp>(op))
      return emitDesc(desc, depth);
    if (isa<scf::YieldOp>(op))
      return success();
    return e.emitArith(op, depth);
  }

  // 주소 하나. 쓰지 않는 쪽은 0x0 이고, pitch 는 물리 주소(33 bit) 바로 위에 얹는다.
  std::string address(Value buf, Value off, Value pitch) {
    if (!buf)
      return "0x0";
    std::string a = "(" + e.name(buf) + " + (uint64_t)" + e.name(off) + ")";
    if (pitch)
      a += " | ((uint64_t)" + e.name(pitch) + " << " +
           std::to_string(aimx::kStrideShift) + ")";
    return a;
  }

  LogicalResult emitDesc(aimx::DescOp desc, unsigned depth) {
    uint32_t status =
        static_cast<uint32_t>(desc.getOpcode()) | batch;
    e.indent(depth);
    os() << "aimx_require(idx + NUM_CHANNELS <= cap, \"the descriptor chain "
            "does not fit its allocation — k or n is larger than the buffer "
            "bound chosen at compile time (raise tile-k or tile-n)\");\n";
    e.indent(depth);
    os() << "PIM_RD_INSTR_MC(&idx, next, "
         << address(desc.getSrc(), desc.getSrcOffset(), desc.getSrcPitch())
         << ", "
         << address(desc.getDst(), desc.getDstOffset(), desc.getDstPitch())
         << ", " << desc.getLen() << "u, 0x";
    os().write_hex(status);
    os() << "u, fpga_id, code);  // "
         << aimx::stringifyOpcode(desc.getOpcode()) << "\n";
    return success();
  }
};

LogicalResult translateAiMXToDescriptors(ModuleOp module, raw_ostream &os) {
  return DescriptorEmitter(os).run(module);
}

} // namespace

void mlir::triton::registerAiMXToDescriptorsTranslation() {
  TranslateFromMLIRRegistration reg(
      "aimx-to-descriptors", "emit the AiMX descriptor programs as C",
      translateAiMXToDescriptors, [](DialectRegistry &registry) {
        // 모듈 전체를 파싱하므로 host 쪽에 나오는 것까지 등록해야 한다.
        registry.insert<arith::ArithDialect, func::FuncDialect,
                        memref::MemRefDialect, scf::SCFDialect,
                        aimx::AiMXDialect>();
      });
}
